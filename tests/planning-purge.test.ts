import {beforeAll,afterAll,describe,it,expect} from "vitest";
import {PGlite} from "@electric-sql/pglite";
import {drizzle} from "drizzle-orm/pglite";
import {eq} from "drizzle-orm";
import * as s from "../src/db/schema";
import {migrateDatabase} from "../src/db/migrate";
import {createService} from "../src/modules/work/service";
import type {Actor,Employee} from "../src/modules/shared/types";
const client=new PGlite(),db=drizzle(client,{schema:s});
const actor:Actor={userId:"admin",employeeId:"admin",isAdmin:true,directReportIds:[]};
const directory:Employee[]=[{userId:"admin",employeeId:"admin",name:"Admin",email:"admin@test.invalid",company:"Test",branch:"",department:"",jobTitle:"",managerId:null}];
const svc=()=>createService(db,actor,directory);
beforeAll(async()=>{await migrateDatabase(client);await db.insert(s.users).values({id:"admin",employeeId:"admin"});});
afterAll(async()=>client.close());
describe("planning lifecycle safety",()=>{
 it("preserves activities when the linked archived task is purged",async()=>{
  const [project]=await db.insert(s.projects).values({name:"Keep plan",ownerId:"admin"}).returning();
  const [task]=await db.insert(s.tasks).values({title:"Delete execution task",creatorId:"admin",projectId:project.id}).returning();
  const [activity]=await db.insert(s.planningActivities).values({projectId:project.id,code:"A1",name:"Plan",taskId:task.id}).returning();
  await svc().archiveTask(task.id);
  await svc().purgeTask(task.id);
  const [still]=await db.select().from(s.planningActivities).where(eq(s.planningActivities.id,activity.id));
  expect(still.taskId).toBeNull();
  expect((await db.select().from(s.tasks).where(eq(s.tasks.id,task.id)))).toHaveLength(0);
 });
 it("purges all planning children atomically when archived project is explicitly purged",async()=>{
  const [project]=await db.insert(s.projects).values({name:"Purge plan",ownerId:"admin"}).returning();
  const [task]=await db.insert(s.tasks).values({title:"Task",creatorId:"admin",projectId:project.id}).returning();
  const [wbs]=await db.insert(s.planningWbs).values({projectId:project.id,code:"1",name:"Root"}).returning();
  await db.insert(s.planningWbs).values({projectId:project.id,parentId:wbs.id,code:"1.1",name:"Child"});
  const [calendar]=await db.insert(s.planningCalendars).values({projectId:project.id,name:"Calendar",timeZone:"Africa/Cairo",workingDays:[0,1,2,3,4],minutesPerDay:480}).returning();
  await db.insert(s.planningCalendarExceptions).values({calendarId:calendar.id,day:"2026-10-18",isWorking:false});
  const [activity]=await db.insert(s.planningActivities).values({projectId:project.id,code:"A",name:"Activity",taskId:task.id,wbsId:wbs.id,calendarId:calendar.id}).returning();
  await db.insert(s.planningProgress).values({projectId:project.id,activityId:activity.id,percentComplete:50,remainingDays:1,updatedBy:"admin"});
  await db.insert(s.planningBaselines).values({projectId:project.id,label:"Frozen",snapshot:{activities:[]},createdBy:"admin"});
  const [resource]=await db.insert(s.planningResources).values({projectId:project.id,name:"Engineer",kind:"labor"}).returning();
  await db.insert(s.planningResourceAssignments).values({projectId:project.id,activityId:activity.id,resourceId:resource.id,plannedHours:1});
  await db.insert(s.planningCostItems).values({projectId:project.id,activityId:activity.id,name:"Cost",currency:"SAR"});
  await db.insert(s.planningRisks).values({projectId:project.id,title:"Risk",probability:2,impact:3});
  await svc().archiveProject(project.id);
  await svc().purgeProject(project.id);
  expect(await db.select().from(s.projects).where(eq(s.projects.id,project.id))).toHaveLength(0);
  expect(await db.select().from(s.planningActivities).where(eq(s.planningActivities.projectId,project.id))).toHaveLength(0);
  expect(await db.select().from(s.planningResources).where(eq(s.planningResources.projectId,project.id))).toHaveLength(0);
 });
});
